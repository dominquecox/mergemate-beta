import { describe, expect, it } from "vitest";
import { checklistMarkdown, fullReviewMarkdown } from "../src/workspace/checklist";
import type { PrFile, ReviewPlan } from "../src/types";

describe("review checklist as Markdown", () => {
  it("renders reading order and unchecked verify items", () => {
    const md = checklistMarkdown({ readingOrder: [{ file: "a.ts", why: "Core change" }], verify: ["Tests cover it.", "No secrets."] });
    expect(md).toBe("## Review checklist\n\n**Read in this order**\n\n1. `a.ts`: Core change\n\n**Verify before approving**\n\n- [ ] Tests cover it.\n- [ ] No secrets.\n");
  });

  it("still renders with nothing to verify", () => {
    expect(checklistMarkdown({ readingOrder: [], verify: [] })).toContain("- [ ] Nothing specific to verify");
  });
});

describe("fullReviewMarkdown", () => {
  const samplePlan: ReviewPlan = {
    readingOrder: [
      { file: "apps/api/migrations/0014_session.sql", why: "Database migration" },
      { file: "apps/api/src/routes/auth.ts", why: "Session endpoint" },
    ],
    verify: ["Verify cookie expiration logic", "Run migration up and down"],
    draftComment: "LGTM! Verified auth flow and migration schema.",
    coverage: { analyzedFiles: 2, skippedFiles: 0, truncatedFiles: 0 },
    model: "meta:muse-spark-1.3",
  };

  const sampleFiles: PrFile[] = [
    { filename: "apps/api/migrations/0014_session.sql", status: "modified", additions: 10, deletions: 0 },
    { filename: "apps/api/src/routes/auth.ts", status: "modified", additions: 25, deletions: 5 },
  ];

  it("generates structured markdown with blast radius and checklist", () => {
    const md = fullReviewMarkdown({
      title: "Add persistent sessions",
      number: 42,
      repo: "owner/repo",
      plan: samplePlan,
      files: sampleFiles,
    });

    expect(md).toContain("## 🔍 MergeMate Review Brief · owner/repo#42");
    expect(md).toContain("**Pull Request**: Add persistent sessions");
    expect(md).toContain("### 💥 Blast Radius & Affected Domains");
    expect(md).toContain("Auth & Identity");
    expect(md).toContain("Database & Schema");
    expect(md).toContain("### 🧭 Suggested Reading Order");
    expect(md).toContain("1. `apps/api/migrations/0014_session.sql`: Database migration");
    expect(md).toContain("2. `apps/api/src/routes/auth.ts`: Session endpoint");
    expect(md).toContain("### ✅ Pre-Approval Verification Checklist");
    expect(md).toContain("- [ ] Verify cookie expiration logic");
    expect(md).toContain("### 💬 Draft Review Comment");
    expect(md).toContain("> LGTM! Verified auth flow and migration schema.");
    expect(md).toContain("Generated by [MergeMate]");
  });

  it("handles missing title and empty files gracefully", () => {
    const md = fullReviewMarkdown({
      plan: {
        readingOrder: [],
        verify: [],
        draftComment: "",
        coverage: { analyzedFiles: 0, skippedFiles: 0, truncatedFiles: 0 },
      },
    });

    expect(md).toContain("## 🔍 MergeMate Review Brief");
    expect(md).not.toContain("### 💥 Blast Radius");
    expect(md).toContain("- [ ] No specific edge cases flagged");
  });
});
