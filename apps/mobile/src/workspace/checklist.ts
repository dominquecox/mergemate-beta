import type { PrFile, ReviewPlan } from "../types";
import { detectBlastRadius } from "./blastRadius";

/** The review plan as a Markdown task list, for pasting into notes. Copy only; MergeMate never posts it. */
export function checklistMarkdown(plan: Pick<ReviewPlan, "readingOrder" | "verify">, title = "Review checklist"): string {
  const lines = [`## ${title}`, ""];
  if (plan.readingOrder.length) {
    lines.push("**Read in this order**", "");
    plan.readingOrder.forEach((item, index) => lines.push(`${index + 1}. \`${item.file}\`: ${item.why}`));
    lines.push("");
  }
  lines.push("**Verify before approving**", "");
  if (plan.verify.length) for (const item of plan.verify) lines.push(`- [ ] ${item}`);
  else lines.push("- [ ] Nothing specific to verify");
  return `${lines.join("\n")}\n`;
}

export interface FullReviewInput {
  title?: string;
  number?: number;
  repo?: string;
  plan: ReviewPlan;
  files?: readonly PrFile[];
}

/**
 * Generates an end-to-end GitHub PR Review in clean Markdown format.
 * Includes blast radius analysis, suggested reading order, checklist, and draft comment.
 * MergeMate is strictly read-only: this string is meant for one-click copy to the clipboard.
 */
export function fullReviewMarkdown(input: FullReviewInput): string {
  const { title, number, repo, plan, files = [] } = input;
  const header = number && repo ? `## 🔍 MergeMate Review Brief · ${repo}#${number}` : `## 🔍 MergeMate Review Brief`;
  const lines: string[] = [header, ""];

  if (title) {
    lines.push(`**Pull Request**: ${title}`, "");
  }

  // Blast Radius section
  const blastDomains = detectBlastRadius(files);
  if (blastDomains.length > 0) {
    lines.push("### 💥 Blast Radius & Affected Domains", "");
    for (const domain of blastDomains) {
      const icon =
        domain.id === "auth"
          ? "🔐"
          : domain.id === "database"
          ? "🗄️"
          : domain.id === "billing"
          ? "💳"
          : domain.id === "security"
          ? "🛡️"
          : domain.id === "dependencies"
          ? "📦"
          : domain.id === "api"
          ? "🌐"
          : "📱";
      const sampleFiles = domain.files.slice(0, 3).map((f) => `\`${f}\``).join(", ");
      const extra = domain.files.length > 3 ? ` and ${domain.files.length - 3} more` : "";
      lines.push(`- ${icon} **${domain.label}**: ${domain.summary} (${sampleFiles}${extra})`);
    }
    lines.push("");
  }

  // Reading order
  if (plan.readingOrder.length > 0) {
    lines.push("### 🧭 Suggested Reading Order", "");
    plan.readingOrder.forEach((item, idx) => {
      lines.push(`${idx + 1}. \`${item.file}\`: ${item.why}`);
    });
    lines.push("");
  }

  // Pre-approval verification
  lines.push("### ✅ Pre-Approval Verification Checklist", "");
  if (plan.verify.length > 0) {
    for (const item of plan.verify) {
      lines.push(`- [ ] ${item}`);
    }
  } else {
    lines.push("- [ ] No specific edge cases flagged");
  }
  lines.push("");

  // Draft review comment
  if (plan.draftComment) {
    lines.push("### 💬 Draft Review Comment", "");
    lines.push(`> ${plan.draftComment.split("\n").join("\n> ")}`, "");
  }

  lines.push("---");
  lines.push("*Generated by [MergeMate](https://mergemate.dev) • Meta Muse Spark co-pilot*");

  return `${lines.join("\n")}\n`;
}
